//! 1 行コメントから正典 URL を取り出す（要件 5.1・5.3・5.6）。
//!
//! # 拾う行の形（設計「取り出しの行の形」）
//!
//! 行頭の空白を除いて [`MARKERS`] のいずれかで始まり、続けて `ukadoc:` があり、
//! その後に空白で区切られた 1 語だけが続いて行末に達する行。この語を URL とみなす。
//!
//! この形は URL を必須にするので、**URL を伴わない「ukadoc」のコメントは 1 件も
//! 拾われない**（要件 5.6。作業ツリーの実測でそういう行は 150 件余りあり、語だけで
//! 判定すると全件が誤検出になる）。
//!
//! # 三択の細目（設計の本文が明示していない箇所と、採った側）
//!
//! - **記号は長い方から照合する**。`///` は `//` でも始まるので、短い方から剥がすと
//!   残りが `/ ukadoc: ...` になって読み違える。長い方から剥がせば `////` や `//!!`
//!   は残りが `ukadoc:` で始まらず、3 種ちょうどに落ち着く。
//! - **`ukadoc:` と URL の間の空白は必須**。設計の「空白で区切られた 1 語」をその
//!   まま採った。空白を求めないと `// ukadoc:上記を参照` のような散文の 1 かたまりが
//!   URL として拾われ、解決の段（設計 D-4 の 3 段目）で検査が赤になる。
//! - **URL の後ろの空白は許す**。行末の空白は編集画面で見えないので、これで落とすと
//!   「書いたのに拾われない」が黙って起きる。語が 2 つ以上続く行だけを落とす。
//! - **記号は字下げを除いた行頭に無ければならない**。証拠の行はそれ 1 行で完結する
//!   （要件 5.3）。コードの尻尾に付いた `let x = 1; // ukadoc: ...` を拾うと、要件
//!   5.4 の語彙表（ページ URL の単独行の直後にスライス定数・設計 D-5）の起点が
//!   定まらなくなる。同じ行の中で引用符が先に来る文字列リテラルも、同じ規則で落ちる。
//!   ただし複数行の生文字列やブロックコメントの中で**行頭から**始まる `// ukadoc:` は
//!   行単位では区別が付かず拾われる。要件 5.2 の「定義箇所だけに置く」と同じく、人が
//!   守る規約の側に残る（設計 D-4）。作業ツリーに該当する行は現在 0 件。
//!
//! ここは純粋層で、ファイルには触らない（要件 6.2）。パスと本文は入出力層の
//! [`crate::io::sources::walk`] が渡す。

use super::UrlHit;

/// 証拠の行に使える 3 種のコメント記号。**長い方から並べる**（照合順がそのまま
/// 優先順位になる）。
const MARKERS: &[&str] = &["///", "//!", "//"];

/// 記号の後に続く目印。
const TOKEN: &str = "ukadoc:";

/// コメント行から正典 URL を取り出す。行番号は返さない（要件 5.1・6.11）。
///
/// `path` はワークスペース根からの相対パスで、拾った証拠にそのまま載せる。`text` は
/// そのファイルの本文。返す並びは**本文に現れた順**で、同じ URL が 2 度現れれば
/// 2 件返す（重複をまとめるのは解決の段の仕事・設計 D-4）。
///
/// 失敗しない。行の形に合わない行は、黙って捨てるのではなく**そもそも証拠ではない**
/// ——ソースの大半は証拠と無関係な行だからである（要件 5.7）。
pub fn extract(path: &str, text: &str) -> Vec<UrlHit> {
    let mut hits = Vec::new();
    for line in text.lines() {
        if let Some(url) = url_of_line(line) {
            hits.push(UrlHit {
                path: path.to_owned(),
                url: url.to_owned(),
            });
        }
    }
    hits
}

/// 1 行から URL を取り出す。形に合わなければ `None`。
fn url_of_line(line: &str) -> Option<&str> {
    let after_marker = strip_marker(line.trim_start())?;
    // 記号と `ukadoc:` の間の空白は任意（設計の「続けて」）。
    let rest = after_marker.trim_start().strip_prefix(TOKEN)?;

    // `ukadoc:` と URL の間の空白は必須。
    if !rest.starts_with(|c: char| c.is_whitespace()) {
        return None;
    }

    // 空白で区切って**ちょうど 1 語**。0 語（空）も 2 語以上（説明文つき）も証拠に
    // しない（要件 5.3）。
    let mut words = rest.split_whitespace();
    let url = words.next()?;
    if words.next().is_some() {
        return None;
    }
    Some(url)
}

/// 行頭（字下げを除いた後）の記号を剥がす。長い記号から順に照合する。
fn strip_marker(trimmed: &str) -> Option<&str> {
    MARKERS
        .iter()
        .find_map(|marker| trimmed.strip_prefix(marker))
}

