//! 本文ハッシュ（設計 D-1）。
//!
//! カタログには ukadoc の本文そのものを載せない（要件 1.3）。載せるのは本文から
//! 作った短い印だけで、本文が変わったかどうかの判定はその印の比較だけで行う
//! （要件 8.2）。ここはその印を作る唯一の場所である。
//!
//! 算法は **FNV-1a の 64 ビット** を自前で持つ（設計 D-1）。理由は 2 つ。
//!
//! - 暗号ライブラリを引くと配布物向けの第三者表記が古くなる。出荷しない調査道具の
//!   ために配布物の謝辞を書き換えるのは筋が悪い。
//! - 標準ライブラリの既定ハッシュは版をまたいだ同値保証が無く、カタログに焼き込む
//!   値としては使えない。
//!
//! 自前で書くことの危うさは、**公表テストベクタ 3 本との逐語一致テスト**で潰す
//! （`hash_tests.rs`）。ここが較正であり、実装を書き換えたら必ずそこが赤になる。
//!
//! 用途は「変わったかどうか」の検出だけで、改竄の検知ではない。

/// この層が使う算法の名前。カタログ冒頭の `hash_algorithm` に記録し、将来
/// 算法を差し替えたときに古いカタログを見分けられるようにする（設計 D-1・D-9）。
pub const HASH_ALGORITHM: &str = "fnv1a64";

/// FNV-1a 64 ビットの初期値（公表定数）。
const OFFSET_BASIS: u64 = 0xcbf2_9ce4_8422_2325;

/// FNV-1a 64 ビットの乗数（公表定数）。
const PRIME: u64 = 0x0000_0100_0000_01b3;

/// 本文のハッシュ。FNV-1a 64 ビットを UTF-8 のバイト列に対して計算し、
/// 16 桁の 16 進小文字を返す。
///
/// 返り値は常に 16 文字である。上位の桁が 0 でも 0 で詰める——桁数が揺れると
/// カタログの列が揃わず、突き合わせが文字列比較でなくなってしまう。
///
/// 同じ入力に対して常に同じ値を返す（設計「純粋層」）。
///
/// # 例
///
/// ```
/// use ukadoc_survey::hash::content_hash;
///
/// assert_eq!(content_hash("foobar"), "85944171f73967e8");
/// ```
pub fn content_hash(text: &str) -> String {
    let mut acc = OFFSET_BASIS;
    for byte in text.as_bytes() {
        // FNV-1a は「先に排他的論理和、後で乗算」。順が逆だと FNV-1 になり別物になる。
        acc ^= u64::from(*byte);
        // 桁溢れは算法の前提なので、debug ビルドで panic しないよう明示的に回す。
        acc = acc.wrapping_mul(PRIME);
    }
    format!("{acc:016x}")
}

